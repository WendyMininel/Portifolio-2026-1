function renderizarCursos() {
    const container = document.getElementById('cursos-container');
    container.innerHTML = '';

    const cursos = modoAtual === 'ads' ? cursosADS : cursosBiomedicina;

    for (const curso of cursos) {
        const cursoCard = document.createElement('div');
        cursoCard.className = 'curso-card';
        cursoCard.dataset.tipo = curso.tipo;
        
        const tipoLabel = curso.tipo === 'curso' ? 'Curso' : 'Certificação';
        
        const linkPDF = curso.link ? curso.link : '#';
        const temLink = curso.link ? true : false;
        
        cursoCard.innerHTML = `
            <h3>${curso.nome}</h3>
            <p><span class="tipo-badge">${tipoLabel}</span></p>
            <p><strong>Instituição:</strong> ${curso.instituicao}</p>
            <p><strong>Carga horária:</strong> ${curso.cargaHoraria}</p>
            <p><strong>Ano:</strong> ${curso.ano}</p>
            <span class="carga-horaria">${curso.cargaHoraria}</span>
            ${temLink ? `<br><a href="${linkPDF}" target="_blank" class="certificado-link">Ver Certificado PDF</a>` : ''}
        `;
        
        container.appendChild(cursoCard);
    }
}



function renderizarProjetos(projetosParaRenderizar) {
    const container = document.getElementById('projetos-container');
    if (!container) return;
    
    container.innerHTML = '';

    if (projetosParaRenderizar.length === 0) {
        container.innerHTML = '<p class="sem-resultados">Nenhum projeto encontrado.</p>';
        return;
    }

    projetosParaRenderizar.forEach(projeto => {
        const projetoCard = document.createElement('div');
        projetoCard.className = 'projeto-card';
        
        const tecnologiasHTML = projeto.tecnologias.map(tech => 
            `<span class="tech-tag">${tech}</span>`
        ).join('');
        
        projetoCard.innerHTML = `
            <div class="projeto-info">
                <h3>${projeto.nome}</h3>
                <p>${projeto.descricao}</p>
                <div class="projeto-tecnologias">
                    ${tecnologiasHTML}
                </div>
                <a href="${projeto.link}" target="_blank" class="projeto-link">
                    Ver projeto <i class="fas fa-external-link-alt"></i>
                </a>
            </div>
        `;
        
        container.appendChild(projetoCard);
    });
}


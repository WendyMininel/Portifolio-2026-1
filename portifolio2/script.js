function pesquisarProjetos(termo) {
    if (!termo) {
        return projetos;
    }
    
    termo = termo.toLowerCase();
    
    return projetos.filter(projeto => {
        const nomeMatch = projeto.nome.toLowerCase().includes(termo);
        const descMatch = projeto.descricao.toLowerCase().includes(termo);
        const techMatch = projeto.tecnologias.some(tech => 
            tech.toLowerCase().includes(termo)
        );
        
        return nomeMatch || descMatch || techMatch;
    });
}

function configurarFiltrosProjetos() {
    const pesquisaInput = document.getElementById('pesquisa-projeto');

    function atualizarProjetos() {
        const termo = pesquisaInput.value;
        const projetosFiltrados = pesquisarProjetos(termo);
        renderizarProjetos(projetosFiltrados);
    }

    if (pesquisaInput) {
        pesquisaInput.addEventListener('input', atualizarProjetos);
    }
}

function filtrarCursosPorTipo(tipo) {
    const container = document.getElementById('cursos-container');
    const cards = container.querySelectorAll('.curso-card');
    
    cards.forEach(card => {
        if (tipo === 'todos') {
            card.style.display = 'block';
        } else {
            if (card.dataset.tipo === tipo) {
                card.style.display = 'block';
            } else {
                card.style.display = 'none';
            }
        }
    });
}

function pesquisarCursos(termo) {
    const container = document.getElementById('cursos-container');
    const cards = container.querySelectorAll('.curso-card');
    
    termo = termo.toLowerCase();
    
    cards.forEach(card => {
        const titulo = card.querySelector('h3').textContent.toLowerCase();
        const instituicao = card.querySelector('p:not(.tipo-badge)')?.textContent.toLowerCase() || '';
        
        if (titulo.includes(termo) || instituicao.includes(termo)) {
            card.style.display = 'block';
        } else {
            card.style.display = 'none';
        }
    });
}

function configurarFiltrosCursos() {
    const pesquisaInput = document.getElementById('pesquisa-curso');
    const botoesFiltro = document.querySelectorAll('.filtro-btn-cursos');
    let tipoAtual = 'todos';

    function atualizarCursos() {
        const termo = pesquisaInput.value;
        
        if (tipoAtual !== 'todos') {
            filtrarCursosPorTipo(tipoAtual);
        } else {
            const container = document.getElementById('cursos-container');
            const cards = container.querySelectorAll('.curso-card');
            cards.forEach(card => card.style.display = 'block');
        }
        
        if (termo) {
            pesquisarCursos(termo);
        }
    }

    if (pesquisaInput) {
        pesquisaInput.addEventListener('input', atualizarCursos);
    }

    botoesFiltro.forEach(botao => {
        botao.addEventListener('click', () => {
            botoesFiltro.forEach(b => b.classList.remove('ativo'));
            botao.classList.add('ativo');
            tipoAtual = botao.dataset.tipo;
            atualizarCursos();
        });
    });
}

